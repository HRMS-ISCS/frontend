import { useQuery } from '@tanstack/react-query';
import clsx from 'clsx';
import { Briefcase, ExternalLink, FileText, FolderOpen, GraduationCap, IdCard, Image, ScrollText } from 'lucide-react';

import { employeesApi } from '@/api';
import { openExternal } from '@/lib/api';
import { Card, EmptyState, ErrorState, Skeleton } from '@/components/ui';

function DocTile({ label, url, contentType, pendingLabel = 'Not uploaded' }) {
  const isImage = contentType?.startsWith('image/');
  const Icon = isImage ? Image : FileText;
  return (
    <button
      type="button"
      disabled={!url}
      onClick={() => openExternal(url)}
      className={clsx(
        'group flex items-center gap-3 rounded-lg border px-3.5 py-3 text-left transition',
        url ? 'border-slate-200 bg-white hover:border-brand-300 hover:shadow-sm' : 'cursor-default border-dashed border-slate-200 bg-slate-50/60',
      )}
    >
      <span
        className={clsx(
          'flex h-9 w-9 shrink-0 items-center justify-center rounded-lg',
          url ? 'bg-brand-50 text-brand-600' : 'bg-slate-100 text-slate-400',
        )}
      >
        <Icon size={17} />
      </span>
      <span className="min-w-0 flex-1">
        <span className={clsx('block truncate text-sm font-medium', url ? 'text-slate-800' : 'text-slate-500')}>{label}</span>
        <span className="block text-xs text-slate-500">{url ? 'Click to view' : pendingLabel}</span>
      </span>
      {url && <ExternalLink size={14} className="text-slate-300 group-hover:text-brand-500" />}
    </button>
  );
}

const PERSONAL = [
  ['profile_photo', 'Profile photo'],
  ['aadhar_card', 'Aadhaar card'],
  ['pan_card', 'PAN card'],
  ['resume', 'Resume'],
];

/**
 * Every stored file for one employee. Signing is Zoho-only, so the legacy
 * font-"signed" policy copies are deliberately not listed; the Zoho-sealed
 * bundle is available to HR from the E-Signatures page.
 */
export function DocumentsPanel({ employeeId }) {
  const { data, isLoading, error, refetch } = useQuery({
    queryKey: ['employee-documents', employeeId],
    queryFn: () => employeesApi.documents(employeeId),
    enabled: Boolean(employeeId),
    retry: false,
  });

  if (isLoading) {
    return (
      <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
        {Array.from({ length: 6 }).map((_, i) => (
          <Skeleton key={i} className="h-16" />
        ))}
      </div>
    );
  }
  if (error?.status === 404) {
    return (
      <Card>
        <EmptyState icon={FolderOpen} title="No documents yet" description="Documents appear here once the personal profile is submitted." />
      </Card>
    );
  }
  if (error) return <Card><ErrorState error={error} onRetry={refetch} /></Card>;

  const personal = data?.personal_documents || {};
  const certs = data?.education_certificates || {};
  const exp = data?.experience_documents || {};
  const contracts = data?.signed_policy_documents || {};
  const contractTiles = [
    ['signed_joining_letter', 'Appointment letter'],
    ['signed_nda', 'Non-disclosure agreement'],
  ]
    .map(([key, label]) => ({ key, label, doc: contracts[key] }))
    .filter(({ doc }) => doc?.sign_status === 'unsigned' || doc?.sign_status === 'not_uploaded');

  return (
    <div className="space-y-5">
      <Card title="Identity & personal" icon={IdCard}>
        <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
          {PERSONAL.map(([key, label]) => (
            <DocTile key={key} label={label} url={personal[key]?.sas_url} contentType={personal[key]?.content_type} />
          ))}
        </div>
      </Card>

      {contractTiles.length > 0 && (
        <Card title="Employment contracts" icon={ScrollText} subtitle="Generated by HR and signed through Zoho Sign">
          <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
            {contractTiles.map(({ key, label, doc }) => (
              <DocTile key={key} label={label} url={doc?.sas_url} contentType="application/pdf" pendingLabel="Not generated yet" />
            ))}
          </div>
        </Card>
      )}

      <Card title="Education certificates" icon={GraduationCap}>
        <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
          {Object.entries(certs).map(([key, doc]) => (
            <DocTile key={key} label={doc.certificate_name || key} url={doc.sas_url} contentType={doc.content_type} />
          ))}
        </div>
      </Card>

      <Card title="Previous employment" icon={Briefcase}>
        <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
          {Object.entries(exp).map(([key, doc]) => (
            <DocTile key={key} label={doc.document_name || key} url={doc.sas_url} contentType={doc.content_type} />
          ))}
        </div>
      </Card>
    </div>
  );
}
